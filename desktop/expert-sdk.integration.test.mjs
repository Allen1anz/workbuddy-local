import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { createRequire } from "node:module";
import { createAppServer } from "../server/app.mjs";
const { createDispatcher } = createRequire(import.meta.url)("./dispatcher.cjs");

test("5.8.3 expert SDK exposes general layout, localized records and filtered pagination", { skip: process.env.WORKBUDDY_PUBLIC_TESTS === "1" ? "Proprietary fixture excluded from public source release" : false }, async t => {
  const dataDir = path.join(await fs.mkdtemp(path.join(os.tmpdir(), "wb-expert-sdk-")), "data");
  const server = createAppServer({ dataDir });
  await new Promise(resolve => server.listen(0, "127.0.0.1", resolve));
  t.after(() => new Promise(resolve => { server.close(resolve); server.closeAllConnections(); }));
  const origin = `http://127.0.0.1:${server.address().port}`;
  const dispatch = createDispatcher({ origin, dataDir, publicExpertCatalog: true });
  const categories = await dispatch("wb:experts.market:categories");
  assert.ok(categories.items.some(category => category.id === "06-ContentCreative"));
  const layout = await dispatch("wb:experts:getPageLayout");
  assert.equal(layout.featuredCategory.type, "expert-featured");
  assert.deepEqual(layout.expertsCategories.map(category => category.type), ["expert", "expert-team"]);
  assert.equal(layout.expertsCategories[0].subCategories[0].categoryId, "all");
  assert.ok(layout.featuredCategory.subCategories.some(scene => scene.experts.length > 0));
  const teams = await dispatch("wb:experts:list", [{ source: "builtin", expertType: "team", page: 2, pageSize: 10 }]);
  assert.equal(teams.items.length, 10);
  assert.ok(teams.total > 20);
  assert.ok(teams.items.every(expert => expert.expertType === "team" && expert.runtimeAvailable === false && typeof expert.name.zh === "string"));
  assert.deepEqual(teams.page, { current: 2, size: 10 });
  const search = await dispatch("wb:experts:list", [{ keyword: "ContentCreator", source: "builtin" }]);
  assert.ok(search.items.some(expert => expert.id === "ContentCreator"));
  assert.ok(search.items.every(expert => JSON.stringify([expert.id, expert.name, expert.displayName, expert.profession, expert.description]).toLowerCase().includes("contentcreator")));
  const detail = await dispatch("wb:experts:get", [{ expertId: "ContentCreator" }]);
  assert.equal(detail.name.zh, "文博凯");
  assert.equal(detail.source, "builtin");
  assert.deepEqual(await dispatch("wb:experts.recents:list"), { items: [] });
  assert.deepEqual((await dispatch("wb:experts.custom:list")).items, []);
  const localPath = path.join(dataDir, "../expert-config/plugins/marketplaces/my-experts/plugins/sdk-local-proof");
  await fs.mkdir(path.join(localPath, ".codebuddy-plugin"), { recursive: true });
  await fs.mkdir(path.join(localPath, "agents"));
  await fs.writeFile(path.join(localPath, ".codebuddy-plugin/plugin.json"), JSON.stringify({ name: "sdk-local-proof", agentName: "main", displayName: "本地SDK测试", description: "Text-only fixture" }));
  await fs.writeFile(path.join(localPath, "agents/main.md"), "Text only. Do not execute tools.");
  const local = (await dispatch("wb:experts.custom:list")).items;
  assert.equal(local.length, 1);
  assert.equal(local[0].localPath, await fs.realpath(localPath));
  assert.equal(local[0].runtimeIdentity, "expert:custom-expert:sdk-local-proof:my-experts");
  await dispatch("wb:experts.recents:add", [{ expertId: local[0].id }]);
  assert.equal((await dispatch("wb:experts.recents:list")).items[0].id, local[0].id);
  await dispatch("wb:experts.recents:remove", [{ expertId: local[0].id }]);
  assert.deepEqual(await dispatch("wb:experts.recents:list"), { items: [] });
  assert.deepEqual(await dispatch("wb:experts:getExpertPageLayout"), { version: 0 });
});
